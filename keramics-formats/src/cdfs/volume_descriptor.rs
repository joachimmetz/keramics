/// CD file system (CDFS) volume descriptor.
pub struct CdFsVolumeDescriptor {
    /// Type indicator.
    pub type_indicator: u8,

    /// Format version.
    pub format_version: u8,

    /// Volume size.
    pub volume_size: u32,

    /// Number of volumes in set.
    pub volumes_in_set: u16,

    /// Index of the volume in the set.
    pub volume_set_index: u16,

    /// Block size.
    pub block_size: u16,

    /// Path table size.
    pub path_table_size: u32,

    /// Type L path table start sector.
    pub path_table_start_sector_le: u32,

    /// Type M path table start sector.
    pub path_table_start_sector_be: u32,
}

impl CdFsVolumeDescriptor {
    /// Creates a new volume descriptor.
    pub fn new() -> Self {
        Self {
            type_indicator: 0,
            format_version: 0,
            volume_size: 0,
            volumes_in_set: 0,
            volume_set_index: 0,
            block_size: 0,
            path_table_size: 0,
            path_table_start_sector_le: 0,
            path_table_start_sector_be: 0,
        }
    }

    /// Reads the volume descriptor from a buffer.
    pub fn read_data(&mut self, data: &[u8]) -> Result<(), ErrorTrace> {
        if data.len() < 2048 {
            return Err(keramics_core::error_trace_new!("Unsupported data size"));
        }
        if &data[1..6] != CDFS_VOLUME_DESCRIPTOR_SIGNATURE {
            return Err(keramics_core::error_trace_new!("Unsupported signature"));
        }
        self.type_indicator = data[0];
        self.format_version = data[6];
        self.volume_size = bytes_to_u32_be!(data, 84);

        let volume_size: u32 = bytes_to_u32_le!(data, 80);
        if self.volume_size != volume_size {
            return Err(keramics_core::error_trace_new!(
                "Mismatch between big- and little-endian volume size"
            ));
        }
        self.volumes_in_set = bytes_to_u16_be!(data, 122);

        let volumes_in_set: u16 = bytes_to_u16_le!(data, 120);
        if self.volumes_in_set != volumes_in_set {
            return Err(keramics_core::error_trace_new!(
                "Mismatch between big- and little-endian number of volumes in set"
            ));
        }
        self.volume_set_index = bytes_to_u16_be!(data, 126);

        let volume_set_index: u16 = bytes_to_u16_le!(data, 124);
        if self.volume_set_index != volume_set_index {
            return Err(keramics_core::error_trace_new!(
                "Mismatch between big- and little-endian volume set index"
            ));
        }
        self.block_size = bytes_to_u16_be!(data, 130);

        let block_size: u16 = bytes_to_u16_le!(data, 128);
        if self.block_size != block_size {
            return Err(keramics_core::error_trace_new!(
                "Mismatch between big- and little-endian block size"
            ));
        }
        self.path_table_size = bytes_to_u32_be!(data, 136);

        let path_table_size: u32 = bytes_to_u32_le!(data, 132);
        if self.path_table_size != path_table_size {
            return Err(keramics_core::error_trace_new!(
                "Mismatch between big- and little-endian path table size"
            ));
        }
        self.path_table_start_sector_le = bytes_to_u32_le!(data, 140);
        self.path_table_start_sector_be = bytes_to_u32_be!(data, 148);

        Ok(())
    }
}

