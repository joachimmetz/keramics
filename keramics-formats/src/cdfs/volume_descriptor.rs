    #[test]
    fn test_read_data() -> Result<(), ErrorTrace> {
        let test_data: Vec<u8> = get_test_data();

        let mut test_struct = CdFsVolumeDescriptor::new();
        test_struct.read_data(&test_data)?;

        assert_eq!(test_struct.type_indicator, 1);
        assert_eq!(test_struct.format_version, 1);
        assert_eq!(test_struct.volume_size, 1212);
        assert_eq!(test_struct.volumes_in_set, 1);
        assert_eq!(test_struct.volume_set_index, 1);
        assert_eq!(test_struct.block_size, 2048);
        assert_eq!(test_struct.path_table_size, 58);
        assert_eq!(test_struct.path_table_start_sector_le, 19);
        assert_eq!(test_struct.path_table_start_sector_be, 21);

        Ok(())
    }

    #[test]
    fn test_read_data_with_unsupported_data_size() {
        let mut test_struct = CdFsVolumeDescriptor::new();

        let test_data: Vec<u8> = get_test_data();
        let result = test_struct.read_data(&test_data[0..2047]);
        assert!(result.is_err());
    }

    #[test]
    fn test_read_data_with_unsupported_signature() {
        let mut test_data: Vec<u8> = get_test_data();
        test_data[1] = 0xff;

        let mut test_struct = CdFsVolumeDescriptor::new();
        let result = test_struct.read_data(&test_data);
        assert!(result.is_err());
    }
